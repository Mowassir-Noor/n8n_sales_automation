#!/usr/bin/env node
// Builds the n8n Workflow SDK sources of the `DB - …` workflows.
//
//   npm run sync:n8n            write dashboard/n8n/build/<slug>.workflow.js
//   npm run sync:n8n -- --check exit 1 when build/ is out of date (CI)
//
// Inputs:
//   n8n/templates/<slug>.workflow.js  SDK code; each Code node has jsCode: '__CODE__(<dir>/<name>)'
//   n8n/code/<dir>/<name>.js          the Code node's JavaScript (top-level `return`, as n8n runs it)
// Inside a code file, a marker region
//   // <shared:NAME>
//   // </shared:NAME>
// is filled with shared/email/NAME.js, and `// <lib:NAME>` … `// </lib:NAME>` with n8n/code/_lib/NAME.js,
// each without its `export { … }` line. The code is then inserted into the template as a JSON string literal.

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, unlinkSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DASHBOARD_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function defaultDirs(opts = {}) {
  const dashboardDir = opts.dashboardDir || DASHBOARD_DIR;
  return {
    dashboardDir,
    sharedDir: opts.sharedDir || join(dashboardDir, 'shared', 'email'),
    libDir: opts.libDir || join(dashboardDir, 'n8n', 'code', '_lib'),
    codeDir: opts.codeDir || join(dashboardDir, 'n8n', 'code'),
    templatesDir: opts.templatesDir || join(dashboardDir, 'n8n', 'templates'),
    buildDir: opts.buildDir || join(dashboardDir, 'n8n', 'build'),
  };
}

class SyncError extends Error {}

// File contents without the ESM export block, so it can live inside a Code node.
export function stripExports(text, label) {
  if (/^\s*import\s/m.test(text)) throw new SyncError(`${label}: has an import statement; shared files must be self-contained`);
  const out = text.replace(/^export\s*\{[^}]*\}\s*;?[ \t]*$/gm, '').replace(/\s+$/, '') + '\n';
  if (/^\s*export\s/m.test(out)) throw new SyncError(`${label}: only a final \`export { … }\` line is allowed`);
  return out;
}

const MARKER_RE = /^([ \t]*)\/\/ <(shared|lib):([A-Za-z0-9_-]+)>[ \t]*\n[\s\S]*?^[ \t]*\/\/ <\/\2:\3>[ \t]*$/gm;

export function expandCode(source, label, opts = {}) {
  const dirs = defaultDirs(opts);
  const opened = (source.match(/\/\/ <(shared|lib):[A-Za-z0-9_-]+>/g) || []).length;
  let replaced = 0;
  const out = source.replace(MARKER_RE, (_m, indent, kind, name) => {
    replaced++;
    const file = kind === 'shared' ? join(dirs.sharedDir, `${name}.js`) : join(dirs.libDir, `${name}.js`);
    if (!existsSync(file)) {
      throw new SyncError(`${label}: marker <${kind}:${name}> needs ${file}, which does not exist` +
        (kind === 'shared' ? ' (the shared email module is written by the shared-email part; see CONTRACT.md)' : ''));
    }
    const body = stripExports(readFileSync(file, 'utf8'), file);
    return `${indent}// <${kind}:${name}>\n${body}${indent}// </${kind}:${name}>`;
  });
  if (replaced !== opened) throw new SyncError(`${label}: a // <shared|lib:NAME> marker has no matching closing marker`);
  return out;
}

export function loadCode(ref, opts = {}) {
  const dirs = defaultDirs(opts);
  if (!/^[a-z0-9-]+\/[a-z0-9-]+$/.test(ref)) throw new SyncError(`bad code reference __CODE__(${ref})`);
  const file = join(dirs.codeDir, `${ref}.js`);
  if (!existsSync(file)) throw new SyncError(`__CODE__(${ref}): ${file} does not exist`);
  return expandCode(readFileSync(file, 'utf8'), file, opts);
}

const PLACEHOLDER_RE = /(['"])__CODE__\(([^)]+)\)\1/g;

export function buildTemplate(text, label, opts = {}) {
  const out = text.replace(PLACEHOLDER_RE, (_m, _q, ref) => JSON.stringify(loadCode(ref.trim(), opts)));
  if (out.includes('__CODE__(')) throw new SyncError(`${label}: unquoted or malformed __CODE__(…) placeholder`);
  const header = `// GENERATED by dashboard/scripts/sync-n8n.mjs from n8n/templates/${label}. Do not edit; run \`npm run sync:n8n\`.\n`;
  return header + out;
}

export function buildAll(opts = {}) {
  const dirs = defaultDirs(opts);
  const result = new Map();
  for (const name of readdirSync(dirs.templatesDir).filter(f => f.endsWith('.workflow.js')).sort()) {
    result.set(name, buildTemplate(readFileSync(join(dirs.templatesDir, name), 'utf8'), name, opts));
  }
  return result;
}

function main(argv) {
  const check = argv.includes('--check');
  const dirs = defaultDirs();
  let built;
  try {
    built = buildAll();
  } catch (e) {
    if (e instanceof SyncError) {
      console.error(`sync-n8n: ${e.message}`);
      return 1;
    }
    throw e;
  }
  const existing = existsSync(dirs.buildDir) ? readdirSync(dirs.buildDir).filter(f => f.endsWith('.workflow.js')) : [];
  const stale = existing.filter(f => !built.has(f));
  const changed = [...built].filter(([name, text]) => {
    const file = join(dirs.buildDir, name);
    return !existsSync(file) || readFileSync(file, 'utf8') !== text;
  }).map(([name]) => name);

  if (check) {
    if (changed.length || stale.length) {
      for (const n of changed) console.error(`sync-n8n --check: n8n/build/${n} is out of date`);
      for (const n of stale) console.error(`sync-n8n --check: n8n/build/${n} has no template`);
      console.error('Run `npm run sync:n8n` and commit the result.');
      return 1;
    }
    console.log(`sync-n8n --check: ${built.size} workflow(s) up to date`);
    return 0;
  }
  mkdirSync(dirs.buildDir, { recursive: true });
  for (const name of changed) writeFileSync(join(dirs.buildDir, name), built.get(name));
  for (const name of stale) unlinkSync(join(dirs.buildDir, name));
  console.log(`sync-n8n: ${built.size} workflow(s), ${changed.length} written, ${stale.length} removed`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
